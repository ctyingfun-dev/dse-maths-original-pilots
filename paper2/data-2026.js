const questions = [];
function add(topic, prompt, correct, wrong, solution, hints, diagram) {
  const n = questions.length + 1;
  const values = [String(correct), ...wrong.map(String)];
  if (new Set(values).size !== 4) throw Error(`第 ${n} 題選項重複`);
  let seed = Math.imul(n, 2654435761) >>> 0;
  seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5;
  const turn = (seed >>> 0) % 4;
  const options = [...values.slice(turn), ...values.slice(0, turn)];
  questions.push({
    n, sourceNo:n, section:n<=30?"甲部":"乙部", topic, prompt, options,
    answer:"ABCD"[options.indexOf(String(correct))], correct:String(correct),
    solution, hints, diagram
  });
}

